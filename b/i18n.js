(() => {
  const norm = (t) => t.replace(/\s+/g, " ").trim();
  const ATTRS = ["aria-label", "alt", "title"];
  const texts = [];   // { node, en, key }
  const attrs = [];   // { el, name, en }

  // Collect every translatable text node and attribute once, from the English page
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => (n.parentElement.closest("script, style") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const key = norm(n.nodeValue);
    if (key && ES[key]) texts.push({ node: n, en: n.nodeValue, key });
  }
  document.querySelectorAll(ATTRS.map((a) => `[${a}]`).join(",")).forEach((el) => {
    ATTRS.forEach((name) => {
      const v = el.getAttribute(name);
      if (v && ES[norm(v)] && !el.closest(".lang")) attrs.push({ el, name, en: v });
    });
  });
  const meta = document.querySelector('meta[name="description"]');
  const head = { title: document.title, desc: meta && meta.content };

  let lang = "en";
  const buttons = document.querySelectorAll(".lang [data-lang]");
  const toggle = document.querySelector(".nav__toggle");

  function apply(next) {
    lang = next;
    const es = lang === "es";
    texts.forEach(({ node, en, key }) => {
      // keep the original leading/trailing whitespace around the words
      node.nodeValue = es ? en.replace(en.trim(), ES[key]) : en;
    });
    attrs.forEach(({ el, name, en }) => el.setAttribute(name, es ? ES[norm(en)] : en));
    document.title = es ? ES[head.title] : head.title;
    if (meta) meta.content = es ? ES[norm(head.desc)] : head.desc;
    document.documentElement.lang = lang;
    buttons.forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
    if (toggle) relabelToggle();
    try { localStorage.setItem("behow-lang", lang); } catch (e) {}
  }

  // script.js resets the menu button label in English when the menu opens or closes
  function relabelToggle() {
    const v = toggle.getAttribute("aria-label");
    const want = lang === "es" ? ES[v] : Object.keys(ES).find((k) => ES[k] === v);
    if (want && want !== v) toggle.setAttribute("aria-label", want);
  }
  if (toggle) new MutationObserver(relabelToggle).observe(toggle, { attributes: true, attributeFilter: ["aria-label"] });

  buttons.forEach((b) => b.addEventListener("click", () => { if (b.dataset.lang !== lang) apply(b.dataset.lang); }));

  // First visit: follow the browser's language; afterwards, remember the choice
  let saved = null;
  try { saved = localStorage.getItem("behow-lang"); } catch (e) {}
  const initial = saved || ((navigator.language || "").toLowerCase().startsWith("es") ? "es" : "en");
  if (initial === "es") apply("es");
})();
